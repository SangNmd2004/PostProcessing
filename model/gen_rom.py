"""
Generate rtl/ldpc/ldpc_code_rom.v from codes.json (the same mother codes the golden model uses).

Usage: python gen_rom.py [ZC]        (default 128)

Row-ordered table   {code, layer, e}  -> col, shift, g (edge index inside the code = C2V RAM address)
Layer table         {code, layer}     -> layer_deg, layer_gap (layer_sched.py) ; num_layers per code
Column-ordered table {code, col, ce}  -> c_layer, c_shift ; col_deg (used by trapping-set post-processing)
"""
import os
import sys

import ir_model as m
import layer_sched as sched

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "rtl", "ldpc", "ldpc_code_rom.v")


def main():
    zc = int(sys.argv[1]) if len(sys.argv) > 1 else 128
    codes = m.load_codes(zc)
    sh_w = max(1, (zc - 1).bit_length())
    names = m.CODE_ORDER
    max_rdeg = max(sum(v >= 0 for v in row) for n in names for row in codes[n])
    max_cdeg = max(sum(row[c] >= 0 for row in codes[n]) for n in names for c in range(m.NCOL))
    max_edges = max(m.edge_list(codes[n])[1] for n in names)
    min_rdeg = min(sum(v >= 0 for v in row) for n in names for row in codes[n])
    min_cdeg = min(sum(row[c] >= 0 for row in codes[n]) for n in names for c in range(m.NCOL))
    assert max_rdeg < 32 and max_cdeg < 8 and max_edges <= 128
    assert min_rdeg >= 2 and min_cdeg >= 2, "decoder registers last_e and needs every degree >= 2"
    for n in names:
        # overlapped layer schedule has no stall logic: a column must never be read while its write is in flight
        assert sched.margin(codes[n]) >= 1, f"{n}: layer overlap hazard"
        assert max(sched.layer_gaps(codes[n])) < (1 << sched.GAP_W), f"{n}: layer_gap does not fit the ROM field"

    L = []
    w = L.append
    w("`timescale 1ns / 1ps")
    w("")
    w("// AUTO-GENERATED by model/gen_rom.py from model/codes.json - do not edit by hand.")
    w(f"// ZC = {zc}. Codes: " + ", ".join(f"{i}={n} ({len(codes[n])} layers, {m.edge_list(codes[n])[1]} edges)"
                                       for i, n in enumerate(names)))
    w(f"// Max row degree {max_rdeg}, max column degree {max_cdeg}.")
    w("module ldpc_code_rom (")
    w("    input      [1:0] code,")
    w("    // row-ordered access (decoding, USC pass)")
    w("    input      [3:0] layer,")
    w("    input      [4:0] e,")
    w("    output reg [3:0] num_layers,")
    w(f"    output reg [{sched.GAP_W - 1}:0] layer_gap,     // last write issue -> next layer's first read issue")
    w("    output reg [4:0] layer_deg,")
    w("    output reg [4:0] e_col,")
    w(f"    output reg [{sh_w - 1}:0] e_shift,")
    w("    output reg [6:0] e_g,")
    w("    // column-ordered access (trapping-set post-processing)")
    w("    input      [4:0] col,")
    w("    input      [2:0] ce,")
    w("    output reg [2:0] col_deg,")
    w("    output reg [3:0] c_layer,")
    w(f"    output reg [{sh_w - 1}:0] c_shift")
    w(");")
    w("")
    w("    always @(*) begin")
    w("        case (code)")
    for i, n in enumerate(names):
        w(f"            2'd{i}: num_layers = 4'd{len(codes[n])};")
    w("            default: num_layers = 4'd0;")
    w("        endcase")
    w("    end")
    w("")
    w("    always @(*) begin")
    w("        case ({code, layer})")
    for i, n in enumerate(names):
        for l, g in enumerate(sched.layer_gaps(codes[n])):
            w(f"            6'd{i * 16 + l}: layer_gap = {sched.GAP_W}'d{g};")
    w(f"            default: layer_gap = {sched.GAP_W}'d2;")
    w("        endcase")
    w("    end")
    w("")
    w("    always @(*) begin")
    w("        case ({code, layer})")
    for i, n in enumerate(names):
        for l, row in enumerate(codes[n]):
            w(f"            6'd{i * 16 + l}: layer_deg = 5'd{sum(v >= 0 for v in row)};")
    w("            default: layer_deg = 5'd0;")
    w("        endcase")
    w("    end")
    w("")
    w("    always @(*) begin")
    w(f"        e_col = 5'd0; e_shift = {sh_w}'d0; e_g = 7'd0;")
    w("        case ({code, layer, e})")
    for i, n in enumerate(names):
        edges, _ = m.edge_list(codes[n])
        for l, es in enumerate(edges):
            for k, (g, c, s) in enumerate(es):
                w(f"            11'd{(i << 9) | (l << 5) | k}: begin e_col = 5'd{c}; e_shift = {sh_w}'d{s}; e_g = 7'd{g}; end")
    w("            default: ;")
    w("        endcase")
    w("    end")
    w("")
    w("    always @(*) begin")
    w("        case ({code, col})")
    for i, n in enumerate(names):
        for c in range(m.NCOL):
            w(f"            7'd{i * 32 + c}: col_deg = 3'd{sum(row[c] >= 0 for row in codes[n])};")
    w("            default: col_deg = 3'd0;")
    w("        endcase")
    w("    end")
    w("")
    w("    always @(*) begin")
    w(f"        c_layer = 4'd0; c_shift = {sh_w}'d0;")
    w("        case ({code, col, ce})")
    for i, n in enumerate(names):
        for c in range(m.NCOL):
            k = 0
            for l, row in enumerate(codes[n]):
                if row[c] >= 0:
                    w(f"            10'd{(i << 8) | (c << 3) | k}: begin c_layer = 4'd{l}; c_shift = {sh_w}'d{row[c]}; end")
                    k += 1
    w("            default: ;")
    w("        endcase")
    w("    end")
    w("")
    w("endmodule")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
