"""Generate the explicit Vivado interface wrapper; the QKD datapath is unchanged."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ports = []
connections = []

def port(direction, name, width=1, interface=None, signal=None, parameter=None):
    if parameter:
        ports.append(f'    (* X_INTERFACE_PARAMETER = "{parameter}" *)')
    if interface:
        kind = 'aximm' if interface == 's_axi' else 'axis'
        ports.append(f'    (* X_INTERFACE_INFO = "xilinx.com:interface:{kind}:1.0 {interface} {signal}" *)')
    vector = f'[{width-1}:0] ' if width > 1 else ''
    ports.append(f'    {direction} wire {vector}{name},')

ports.extend([
    '    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 s_axi_aclk CLK" *)',
    '    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axi:s_axis_ch:s_axis_syn:s_axis_pa_x:s_axis_pa_seed:m_axis_key:m_axis_pa_y, ASSOCIATED_RESET s_axi_aresetn, FREQ_HZ 50000000" *)',
    '    input wire s_axi_aclk,',
    '    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 s_axi_aresetn RST" *)',
    '    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)',
    '    input wire s_axi_aresetn,',
])
connections.extend(['.s_axi_aclk(s_axi_aclk)', '.s_axi_aresetn(s_axi_aresetn)'])
axi = [
    ('input','awaddr',32), ('input','awprot',3), ('input','awvalid',1), ('output','awready',1),
    ('input','wdata',32), ('input','wstrb',4), ('input','wvalid',1), ('output','wready',1),
    ('output','bresp',2), ('output','bvalid',1), ('input','bready',1),
    ('input','araddr',32), ('input','arprot',3), ('input','arvalid',1), ('output','arready',1),
    ('output','rdata',32), ('output','rresp',2), ('output','rvalid',1), ('input','rready',1),
]
for direction, signal, width in axi:
    name = 's_axi_' + signal
    parameter = 'PROTOCOL AXI4LITE, DATA_WIDTH 32, ADDR_WIDTH 32' if signal == 'awaddr' else None
    port(direction, name, width, 's_axi', signal.upper(), parameter)
    if signal not in ('awprot', 'arprot'):
        value = name + '[7:0]' if signal in ('awaddr', 'araddr') else name
        connections.append(f'.{name}({value})')

for bus in ('s_axis_ch', 's_axis_syn', 's_axis_pa_x', 's_axis_pa_seed', 'm_axis_key', 'm_axis_pa_y'):
    source = bus.startswith('m_')
    width = 64 if source else 32
    forward, reverse = ('output', 'input') if source else ('input', 'output')
    for signal, bits, direction in [('tdata',width,forward), ('tkeep',width//8,forward),
                                    ('tlast',1,forward), ('tvalid',1,forward), ('tready',1,reverse)]:
        port(direction, bus + '_' + signal, bits, bus, signal.upper())
        if signal not in ('tkeep', 'tlast') or (source and signal == 'tlast'):
            connections.append(f'.{bus}_{signal}({bus}_{signal})')
    if bus == 'm_axis_key':
        port('output', 'm_axis_key_tuser', 2, bus, 'TUSER')
        connections.append('.m_axis_key_tuser(m_axis_key_tuser)')

ports.extend(['    (* X_INTERFACE_INFO = "xilinx.com:signal:interrupt:1.0 irq INTERRUPT" *)',
              '    (* X_INTERFACE_PARAMETER = "SENSITIVITY LEVEL_HIGH" *)',
              '    output wire irq'])
connections.append('.irq(irq)')
text = '''`timescale 1ns / 1ps
// Generated by syn/zc702/generate_wrapper.py. Fixed ZC=128, CTX_W=2.
// Full-word AXI-Lite writes only: the original IP ignores WSTRB.
// Input DMA packets must have full TKEEP and exact configured word counts.
// TLAST on input is unused: original packers delimit blocks by word count.
// KEY TUSER is a context tag; simple DMA does not retain it in DDR.
// Initial software bring-up therefore uses context 0 only.
module qkd_pp_zc702 (
'''
text += '\n'.join(ports) + '\n);\n'
text += "    assign m_axis_key_tkeep = 8'hff;\n    assign m_axis_pa_y_tkeep = 8'hff;\n"
text += '    qkd_pp_axi #(.ZC(128), .SH_W(7), .CTX_W(2)) u_qkd (\n'
text += ',\n'.join('        ' + x for x in connections) + '\n    );\nendmodule\n'
dest = ROOT / 'rtl/top/qkd_pp_zc702.v'
dest.write_text(text, encoding='utf-8')
print(dest)
